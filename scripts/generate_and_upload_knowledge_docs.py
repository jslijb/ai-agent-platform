def get_existing_documents():
    try:
        resp = requests.get(LIST_API, headers={"x-test-user-id": USER_ID}, timeout=30)
        data = resp.json()
        if data.get("success"):
            docs = data.get("documents", [])
            existing = set()
            for doc in docs:
                fname = doc.get("fileName", "")
                existing.add(fname)
            return existing
        return set()
    except Exception as e:
        logger.warning(f"获取文档列表异常: {e}")
        return set()


def upload_file(file_path):
    filename = os.path.basename(file_path)
    try:
        with open(file_path, "rb") as f:
            files = {"file": (filename, f, "text/plain")}
            headers = {"x-test-user-id": USER_ID}
            resp = requests.post(UPLOAD_API, files=files, headers=headers, timeout=600)
        data = resp.json()
        if data.get("success"):
            logger.info(f"上传成功: {filename}, documentId={data.get('documentId')}, 分块数={data.get('chunkCount')}")
            return True
        else:
            logger.error(f"上传失败: {filename}, 原因: {data.get('message', '未知')}")
            return False
    except Exception as e:
        logger.error(f"上传异常: {filename}, 原因: {e}")
        return False


